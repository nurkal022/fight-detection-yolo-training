#!/usr/bin/env python3
"""
Export YOLO Dataset
Экспорт размеченных данных в стандартный формат YOLO для обучения

Создает структуру:
    yolo_dataset/
        images/
            train/
            val/
        labels/
            train/
            val/
        classes.txt
        data.yaml

Использование:
    python export_yolo_dataset.py [--val-split 0.2]
"""

import json
import random
import shutil
import argparse
from pathlib import Path

SCRIPT_DIR = Path(__file__).parent.absolute()
DATASET_DIR = SCRIPT_DIR / 'dataset'
ANNOTATIONS_DIR = SCRIPT_DIR / 'annotations'
CLASSES_FILE = SCRIPT_DIR / 'dataset_classes.json'
OUTPUT_DIR = SCRIPT_DIR / 'yolo_dataset'


def load_classes():
    """Загрузить имена классов"""
    if not CLASSES_FILE.exists():
        print(f"❌ Файл {CLASSES_FILE} не найден!")
        return []
    
    with open(CLASSES_FILE, 'r', encoding='utf-8') as f:
        config = json.load(f)
    
    return [cls['name'] for cls in config.get('classes', [])]


def get_annotated_images():
    """Получить список изображений с аннотациями"""
    annotated = []
    
    if not ANNOTATIONS_DIR.exists():
        print("⚠️  Директория аннотаций не найдена")
        return []
    
    for txt_file in ANNOTATIONS_DIR.rglob('*.txt'):
        # Проверяем что файл не пустой
        if txt_file.stat().st_size == 0:
            continue
        
        # Находим соответствующее изображение
        relative = txt_file.relative_to(ANNOTATIONS_DIR)
        
        # Пробуем разные расширения
        for ext in ['.jpg', '.jpeg', '.png']:
            img_path = DATASET_DIR / relative.parent / (txt_file.stem + ext)
            if img_path.exists():
                annotated.append({
                    'image': img_path,
                    'label': txt_file
                })
                break
    
    return annotated


def export_dataset(val_split: float = 0.2):
    """Экспортировать датасет"""
    print("=" * 50)
    print("YOLO Dataset Export")
    print("=" * 50)
    
    # Загружаем классы
    class_names = load_classes()
    if not class_names:
        return
    
    print(f"✅ Классы: {', '.join(class_names)}")
    
    # Получаем аннотированные изображения
    annotated = get_annotated_images()
    if not annotated:
        print("❌ Нет аннотированных изображений!")
        return
    
    print(f"✅ Найдено {len(annotated)} аннотированных изображений")
    
    # Перемешиваем и разделяем на train/val
    random.shuffle(annotated)
    val_count = int(len(annotated) * val_split)
    val_set = annotated[:val_count]
    train_set = annotated[val_count:]
    
    print(f"   Train: {len(train_set)} изображений")
    print(f"   Val: {len(val_set)} изображений")
    
    # Создаем директории
    output = OUTPUT_DIR
    if output.exists():
        shutil.rmtree(output)
    
    (output / 'images' / 'train').mkdir(parents=True)
    (output / 'images' / 'val').mkdir(parents=True)
    (output / 'labels' / 'train').mkdir(parents=True)
    (output / 'labels' / 'val').mkdir(parents=True)
    
    # Копируем файлы
    def copy_set(items, split_name):
        for item in items:
            img_dest = output / 'images' / split_name / item['image'].name
            lbl_dest = output / 'labels' / split_name / (item['image'].stem + '.txt')
            
            shutil.copy2(item['image'], img_dest)
            shutil.copy2(item['label'], lbl_dest)
    
    copy_set(train_set, 'train')
    copy_set(val_set, 'val')
    
    # Создаем classes.txt
    with open(output / 'classes.txt', 'w') as f:
        for name in class_names:
            f.write(f"{name}\n")
    
    # Создаем data.yaml для YOLO
    yaml_content = f"""# YOLO Dataset Configuration
# Generated by export_yolo_dataset.py

path: {output.absolute()}
train: images/train
val: images/val

nc: {len(class_names)}
names: {class_names}
"""
    
    with open(output / 'data.yaml', 'w') as f:
        f.write(yaml_content)
    
    print()
    print("=" * 50)
    print(f"✅ Датасет экспортирован в: {output}")
    print()
    print("Структура:")
    print(f"   {output}/")
    print(f"   ├── images/")
    print(f"   │   ├── train/ ({len(train_set)} файлов)")
    print(f"   │   └── val/ ({len(val_set)} файлов)")
    print(f"   ├── labels/")
    print(f"   │   ├── train/")
    print(f"   │   └── val/")
    print(f"   ├── classes.txt")
    print(f"   └── data.yaml")
    print()
    print("Для обучения YOLOv8:")
    print(f"   yolo detect train data={output}/data.yaml model=yolov8n.pt epochs=100")
    print("=" * 50)


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description='Export annotated dataset to YOLO format')
    parser.add_argument('--val-split', type=float, default=0.2, 
                        help='Доля данных для валидации (по умолчанию 0.2)')
    
    args = parser.parse_args()
    export_dataset(args.val_split)
